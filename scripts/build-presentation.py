def para(text, x, y, width=840, size=18, color=ink, leading=None):
    style = ParagraphStyle('p', fontName='Deck', fontSize=size, leading=leading or size*1.4, textColor=HexColor(color))
    p = Paragraph(text, style)
    _, height = p.wrap(width, H)
    p.drawOn(c, x, y-height)
    return y-height

